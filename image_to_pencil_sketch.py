import numpy as np
from PIL import Image

CHARS = "@%#*+=-:. "  # dark -> light

def to_ascii(path, width=80):
    img = Image.open(path).convert("L")           # grayscale
    height = int(img.height / img.width * width * 0.5)  # 0.5 because characters are taller than wide
    px = np.array(img.resize((width, height)))
    idx = (px / 255 * (len(CHARS) - 1)).astype(int)
    return "\n".join("".join(CHARS[i] for i in row) for row in idx)

import cv2
import matplotlib.pyplot as plt
from google.colab import files

name = list(files.upload())[0]
img = cv2.imread(name)

gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
inv = 255 - gray                          # invert
blur = cv2.GaussianBlur(inv, (21, 21), 0) # blur the inverted image
sketch = cv2.divide(gray, 255 - blur, scale=256)  # color-dodge blend

cv2.imwrite("sketch.png", sketch)
plt.figure(figsize=(8, 8))
plt.imshow(sketch, cmap="gray")
plt.axis("off")
plt.show()

gray_sk, color_sk = cv2.pencilSketch(img, sigma_s=60, sigma_r=0.07, shade_factor=0.05)

plt.figure(figsize=(12, 6))
plt.subplot(1, 2, 1); plt.imshow(gray_sk, cmap="gray"); plt.axis("off"); plt.title("Graphite")
plt.subplot(1, 2, 2); plt.imshow(cv2.cvtColor(color_sk, cv2.COLOR_BGR2RGB)); plt.axis("off"); plt.title("Color pencil")
plt.show()